// Resolve the canonical English source for a live DOM string.
// React re-uses text nodes across renders, so a cached source can go stale
// (e.g. badge "3" -> "4", or a new patient name). If the current content
// recovers to something DIFFERENT from the cache, React rendered fresh
// content and the fresh value wins. If it recovers to the cache, the
// current content is just a translation of the cached source.
export function resolveNodeSource(current, cached) {
  if (current == null) return cached ?? current;
  const fromCurrent = recoverEnglishSource(current);
  if (cached == null) return fromCurrent;
  if (fromCurrent === cached) return cached;
  // Current holds a translation of the cached source (normal case).
  if (translatedFromEnglish(cached, 'Hindi') === current
    || translatedFromEnglish(cached, 'Bengali') === current
    || translatedFromEnglish(cached, 'Tamil') === current) return cached;
  // Otherwise React rendered something new (fresh English, user data, AI
  // text) — adopt it and never "restore" it to the stale cache.
  return fromCurrent;
}

export function shouldSkipNode(node) {
  const parent = node.parentElement;
  if (!parent) return true;
  const tag = parent.tagName;
  // NOTE: OPTION/SELECT are intentionally NOT skipped so dropdown items,
  // sort/filter selects and other small blocks translate too. The language
  // <select> itself is protected via data-no-translate.
  if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'NOSCRIPT') return true;
  if (parent.closest?.('[data-no-translate]')) return true;
  return false;
}

const TRANSLATABLE_ATTRIBUTES = ['placeholder', 'title', 'aria-label', 'alt', 'value'];

function shouldSkipAttribute(element, attribute) {
  if (element.closest?.('[data-no-translate]')) return true;
  if (element.tagName === 'OPTION' && element.closest?.('select[data-no-translate]')) return true;
  // Never rewrite user-typed text — only button labels carry a translatable value.
  if (attribute === 'value') {
    const tag = element.tagName;
    if (tag === 'OPTION') return false;
    if (tag !== 'INPUT' && tag !== 'BUTTON') return true;
    const type = (element.getAttribute('type') || '').toLowerCase();
    if (tag === 'INPUT' && !['button', 'submit', 'reset'].includes(type)) return true;
  }
  return false;
}

export function translateTree(language) {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    if (shouldSkipNode(node)) return;
    const current = node.nodeValue;
    if (!current || !current.trim()) return;
    const englishSource = resolveNodeSource(current, node.__dashboardSource ?? null);
    node.__dashboardSource = englishSource;
    const next = language === 'English' ? englishSource : translatedFromEnglish(englishSource, language);
    if (node.nodeValue !== next) node.nodeValue = next;
  });
  document.querySelectorAll('[placeholder], [title], [aria-label], [alt], input[value], input[type="submit"], input[type="button"]').forEach((element) => {
    if (shouldSkipAttribute(element, 'placeholder') && shouldSkipAttribute(element, 'value')) {
      if (element.closest?.('[data-no-translate]')) return;
    }
    TRANSLATABLE_ATTRIBUTES.forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;
      if (shouldSkipAttribute(element, attribute)) return;
      const key = `dashboard${attribute.replace(/-([a-z])/g, (_, c) => c.toUpperCase())}`;
      const raw = element.getAttribute(attribute);
      const englishSource = resolveNodeSource(raw, element.dataset[key] ?? null);
      element.dataset[key] = englishSource;
      const next = language === 'English' ? englishSource : translatedFromEnglish(englishSource, language);
      if (element.getAttribute(attribute) !== next) element.setAttribute(attribute, next);
    });
  });
}
