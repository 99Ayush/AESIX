export const LANG_ORDER = ['Hindi', 'Bengali', 'Tamil'];

// Reverse lookup: any known string (English or any translation) -> canonical English key.
const reverseExact = new Map();
Object.entries(words).forEach(([english, values]) => {
  reverseExact.set(english.toLowerCase(), english);
  values.forEach((v) => reverseExact.set(String(v).toLowerCase(), english));
});
const entriesByLengthDesc = Object.entries(words)
  .filter(([english]) => english.length > 2)
  .sort(([a], [b]) => b.length - a.length);

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// ASCII single-word keys (All, Add, Age, Sort, Copy...) must only replace whole
// words — otherwise "Age" would corrupt "Stage"/"Message" and "Add" -> "Address".
function replaceSegment(haystack, needle, replacement) {
  if (!needle || needle.length <= 2) return haystack.split(needle).join(replacement);
  // eslint-disable-next-line no-control-regex
  if (/^[\w]+$/.test(needle) && /^[\x00-\x7F]+$/.test(needle)) {
    try {
      return haystack.replace(new RegExp(`\\b${escapeRegExp(needle)}\\b`, 'g'), replacement);
    } catch {
      return haystack.split(needle).join(replacement);
    }
  }
  return haystack.split(needle).join(replacement);
}

// Strip leading/trailing non-alphanumeric affixes (emoji, •, ✓, ✕, +, →, ↗, :).
// \p{M} (combining marks: Devanagari ं, Tamil vowel signs, Bengali kar) counts
// as word content — otherwise lookups like "अस्वीकार करें" silently miss.
function stripAffixes(text) {
  const value = text.trim();
  const leading = value.match(/^[^\p{L}\p{N}\p{M}]+/u)?.[0] || '';
  const withoutLeading = value.slice(leading.length);
  const trailing = withoutLeading.match(/[^\p{L}\p{N}\p{M}]+$/u)?.[0] || '';
  const key = withoutLeading.slice(0, trailing ? -trailing.length : undefined).trim();
  return { value, leading, trailing, key };
}

export function recoverEnglishSource(text) {
  if (!text) return text;
  const trimmed = text.trim();
  if (!trimmed) return text;
  const leadingOuter = text.slice(0, text.indexOf(trimmed));
  const trailingOuter = text.slice(text.indexOf(trimmed) + trimmed.length);
  const { leading, trailing, key } = stripAffixes(text);
  if (!key) return text;
  const exact = reverseExact.get(key.toLowerCase());
  if (exact) return `${leadingOuter}${leading}${exact}${trailing}${trailingOuter}`;
  let result = text;
  entriesByLengthDesc.forEach(([english, values]) => {
    values.forEach((v) => {
      if (v && v.length > 2) result = replaceSegment(result, v, english);
    });
  });
  return result;
}

export function translatedFromEnglish(englishText, language) {
  if (language === 'English') return englishText;
  const index = LANG_ORDER.indexOf(language);
  if (index === -1) return englishText;
  const trimmed = englishText.trim();
  if (!trimmed) return englishText;
  const leadingOuter = englishText.slice(0, englishText.indexOf(trimmed));
  const trailingOuter = englishText.slice(englishText.indexOf(trimmed) + trimmed.length);
  const { leading, trailing, key } = stripAffixes(englishText);
  if (!key) return englishText;
  const entry = Object.entries(words).find(([en]) => en.toLowerCase() === key.toLowerCase());
  if (entry) {
    return `${leadingOuter}${leading}${entry[1][index]}${trailing}${trailingOuter}`;
  }
  return entriesByLengthDesc.reduce(
    (result, [en, values]) => replaceSegment(result, en, values[index]),
    englishText,
  );
}

export function translated(text, language) {
  if (language === 'English') return recoverEnglishSource(text);
  const englishSource = recoverEnglishSource(text);
  return translatedFromEnglish(englishSource, language);
}

